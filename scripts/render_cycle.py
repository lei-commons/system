"""Render the daily cycle (Cloud Workflows) from the sources registry and config/cycle.yaml.

    python scripts/render_cycle.py           # writes infra/workflows/daily-cycle.yaml
    python scripts/render_cycle.py --check   # exits 1 if the committed file is out of date

Terraform (infra/terraform/cycle.tf) and deploy-cycle.yml both deploy the committed file, so the two
never disagree. Each source is independent (owner decision 2026-11-18): every ingestion job is tried in
the registry's order; a failure is logged and the cycle carries on; the sources still failing are tried
again after ``retry_wait_minutes``, up to ``retries`` rounds; then the snapshot and the database load
run (these two still stop the cycle if they fail); finally, if any source never succeeded, the cycle
ends as failed, naming them, so the owner is alerted and the day isn't counted as clean.

Sources on trial (config/sources.yaml pipeline stage, owner 2026-11-22; docs/source-trials.md) run last,
after the snapshot, the load and the DeDi check, once each, and only measure (a publication already measured
with the deployed code is a seconds-long check): a failing trial is logged (trial-failed) and never fails the
cycle or delays the production data. With no source on trial there is no trials step.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "config" / "sources.yaml"
CONFIG = ROOT / "config" / "cycle.yaml"
OUT = ROOT / "infra" / "workflows" / "daily-cycle.yaml"
REGION = "us-central1"
AFTER_INGEST = ["build-snapshot", "load-db"]

HEADER = """\
# GENERATED by scripts/render_cycle.py from config/sources.yaml, config/cycle.yaml, config/dedi.yaml,
# config/web_claims.yaml and the approved browser fallbacks (config/egress-allowlist.yaml). Don't edit:
# change those and run the script. Deployed by Terraform (infra/terraform/cycle.tf) and by
# .github/workflows/deploy-cycle.yml, which deploy this same file.
"""


sys.path.insert(0, str(ROOT / "packages" / "lc_core"))
from lc_core.cycle import CycleConfigError as ConfigError  # noqa: E402
from lc_core.cycle import settings, timeout_seconds  # noqa: E402


def ingest_jobs(registry: dict, stage: str = "production") -> list:
    """The ingestion jobs of one stage, in registry order (every job's name checked, whatever its stage)."""
    built = [s["pipeline"] for s in registry.get("sources", []) if (s.get("pipeline") or {}).get("job")]
    for pipeline in built:
        if pipeline.get("stage") not in ("trial", "production"):
            raise ConfigError(f"job {pipeline['job']}: pipeline stage must be trial or production")
    _check_names([p["job"] for p in built])
    return [p["job"] for p in built if p["stage"] == stage]


def _check_names(jobs: list) -> None:
    if len(jobs) != len(set(jobs)):
        raise ConfigError("two sources share a job")
    for job in jobs:
        if not job.replace("-", "").isalnum() or not job.startswith("ingest-"):
            raise ConfigError(f"job name {job!r} must be ingest-<letters, digits, dashes>")


def _run(job_expr: str, timeout: int) -> dict:
    """Run a job and wait for it, up to ``timeout`` seconds (config/cycle.yaml timeouts_minutes)."""
    return {"call": "googleapis.run.v2.projects.locations.jobs.run",
            "args": {"name": '${"projects/" + project + "/locations/" + region + "/jobs/" + ' + job_expr + "}",
                     "connector_params": {"timeout": timeout}}}


def _try_source(round_expr: str, prefix: str, timeout: int) -> list:
    """Run ``job``; on failure log it and add it to ``failed`` (the loop carries on). Step names are
    prefixed: Workflows wants every step name unique."""
    return [{f"{prefix}_run": {
        "try": _run("job", timeout),
        "except": {"as": "e", "steps": [
            {f"{prefix}_note_failure": {"assign": [{"failed": "${list.concat(failed, job)}"}]}},
            {f"{prefix}_log_failure": {"call": "sys.log", "args": {"severity": "WARNING", "json": {
                "event": "source-failed", "job": "${job}", "round": round_expr, "error": "${e}"}}}},
        ]},
    }}]


# One real, quick and harmless job; one missing job whose "browser fallback" is that real job (so it
# recovers); one missing job with no fallback (so it stays failed).
SELFTEST_JOBS = ["egress-check", "ingest-selftest-missing", "ingest-selftest-gone"]


def render(registry: dict, config: dict, selftest: bool = False, fallbacks: dict = None, dedi: bool = False,
           web_claims: bool = False) -> dict:
    """The cycle. ``selftest``: the same logic over SELFTEST_JOBS, one retry after a minute, and no snapshot
    or load, to prove in Workflows itself that a failing source is retried and skipped (deploy-cycle.yml)."""
    s_all = s = settings(config)
    default_timeout = timeout_seconds(s_all, "default")
    jobs = ingest_jobs(registry)
    trials = [] if selftest else ingest_jobs(registry, "trial")
    fallbacks = dict(fallbacks or {})  # {regular job: fallback job}, only those the owner approved
    if selftest:
        s, jobs = {"retry_wait_minutes": 1, "retries": 1}, SELFTEST_JOBS
        fallbacks = {"ingest-selftest-missing": "egress-check"}  # the fallback path: the missing job "recovers"
    steps = [
        {"init": {"assign": [
            {"project": '${sys.get_env("GOOGLE_CLOUD_PROJECT_ID")}'},
            {"region": REGION},
            {"sources": jobs},
            {"failed": []},
        ] + ([{"fallbacks": fallbacks}] if fallbacks else [])}},
        {"first_try": {"for": {"value": "job", "in": "${sources}", "steps": _try_source("${0}", "first", default_timeout)}}},
    ]
    if s["retries"]:
        steps.append({"retry_rounds": {"for": {"value": "retry_round", "range": [1, s["retries"]], "steps": [
            {"all_done": {"switch": [{"condition": "${len(failed) == 0}", "next": "break"}]}},
            {"wait": {"call": "sys.sleep", "args": {"seconds": s["retry_wait_minutes"] * 60}}},
            {"take_failed": {"assign": [{"trying": "${failed}"}, {"failed": []}]}},
            {"retry_each": {"for": {"value": "job", "in": "${trying}", "steps": _try_source("${retry_round}", "retry", default_timeout)}}},
        ]}}})
    if fallbacks:
        # A source still failing after its retries, with an approved browser fallback: its fallback job runs
        # once (it checks the source's health itself and never runs around a refusal). Success: recovered.
        steps.append({"browser_fallbacks": {"steps": [
            {"take_still_failing": {"assign": [{"trying": "${failed}"}, {"failed": []}]}},
            {"fallback_each": {"for": {"value": "job", "in": "${trying}", "steps": [
                {"has_fallback": {"switch": [{"condition": "${job in fallbacks}", "next": "fallback_run"}],
                                  "next": "no_fallback"}},
                {"no_fallback": {"assign": [{"failed": "${list.concat(failed, job)}"}], "next": "continue"}},
                {"fallback_run": {
                    "try": {"steps": [
                        {"fallback_job": _run("fallbacks[job]", default_timeout)},
                        {"fallback_log": {"call": "sys.log", "args": {"severity": "WARNING", "json": {
                            "event": "source-recovered-by-browser", "job": "${job}"}}}},
                    ]},
                    "except": {"as": "e", "steps": [
                        {"fallback_note_failure": {"assign": [{"failed": "${list.concat(failed, job)}"}]}},
                        {"fallback_log_failure": {"call": "sys.log", "args": {"severity": "WARNING", "json": {
                            "event": "browser-fallback-failed", "job": "${job}", "error": "${e}"}}}},
                    ]},
                }},
            ]}}},
        ]}})
    steps += [{job.replace("-", "_"): _run(f'"{job}"', timeout_seconds(s_all, job))} for job in ([] if selftest else AFTER_INGEST)]
    if dedi and not selftest:
        # The DeDi watchdog (docs/dedi.md): checks the published set and republishes if needed. Non-fatal: the
        # day's data is already served; a failure is logged here and the job's own alert emails the owner.
        steps.append({"dedi_check": {
            "try": _run('"dedi-check"', timeout_seconds(s_all, "dedi-check")),
            "except": {"as": "e", "steps": [{"dedi_check_failed": {"call": "sys.log", "args": {
                "severity": "WARNING", "json": {"event": "dedi-check-failed", "error": "${e}"}}}}]},
        }})
    if trials:
        # Sources on trial: once each, after everything production needs. A failure is logged, never fatal.
        steps.append({"trials": {"for": {"value": "job", "in": trials, "steps": [{"trial_run": {
            "try": _run("job", default_timeout),
            "except": {"as": "e", "steps": [{"trial_log_failure": {"call": "sys.log", "args": {
                "severity": "WARNING", "json": {"event": "trial-failed", "job": "${job}", "error": "${e}"}}}}]},
        }}]}}})
    if web_claims and not selftest:
        # The web-asserted facts pilot (config/web_claims.yaml; owner approval 2026-11-23): measure-only, started
        # last of all and not waited for (skip_polling), so the cycle ends as before while the pilot works for a few
        # hours (its own task timeout, config/cycle.yaml timeouts_minutes.web-claims). Not starting is logged, never fatal.
        start = _run('"web-claims"', timeout_seconds(s_all, "web-claims"))
        start["args"]["connector_params"]["skip_polling"] = True
        steps.append({"web_claims": {
            "try": start,
            "except": {"as": "e", "steps": [{"web_claims_failed": {"call": "sys.log", "args": {
                "severity": "WARNING", "json": {"event": "web-claims-failed", "error": "${e}"}}}}]},
        }})
    steps += [
        {"report": {"switch": [{"condition": "${len(failed) > 0}", "steps": [{"fail": {"raise": {
            "code": "sources-failed",
            "message": f"sources still failing after {s['retries']} retries (the snapshot and load ran without their new data)",
            "failed": "${failed}"}}}]}]}},
        {"done": {"return": {"sources": "${sources}", "failed": "${failed}"}}},
    ]
    return {"main": {"steps": steps}}


def approved_fallbacks() -> dict:
    """{regular job: fallback job} for the browser fallbacks whose hosts the owner approved."""
    from lc_core.sources import browser_fallbacks

    return {job: c["job"] for job, c in browser_fallbacks(REGISTRY, ROOT / "config" / "egress-allowlist.yaml").items()}


def dedi_enabled() -> bool:
    """Whether DeDi publication is on (config/dedi.yaml enabled): then the cycle checks it after the load."""
    path = ROOT / "config" / "dedi.yaml"
    return path.exists() and (yaml.safe_load(path.read_text()) or {}).get("enabled") is True


def web_claims_enabled() -> bool:
    """Whether the web-asserted facts pilot is on (config/web_claims.yaml enabled): then it runs last."""
    path = ROOT / "config" / "web_claims.yaml"
    return path.exists() and (yaml.safe_load(path.read_text()) or {}).get("enabled") is True


def text(registry: dict, config: dict, selftest: bool = False) -> str:
    return HEADER + yaml.safe_dump(render(registry, config, selftest, None if selftest else approved_fallbacks(),
                                          dedi=not selftest and dedi_enabled(),
                                          web_claims=not selftest and web_claims_enabled()),
                                   sort_keys=False, width=200)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", metavar="PATH", help="write the self-test cycle to PATH instead")
    a = ap.parse_args(argv)
    if a.selftest:
        Path(a.selftest).write_text(text(yaml.safe_load(REGISTRY.read_text()), yaml.safe_load(CONFIG.read_text()), True))
        print(f"wrote {a.selftest}")
        return 0
    try:
        wanted = text(yaml.safe_load(REGISTRY.read_text()), yaml.safe_load(CONFIG.read_text()))
    except ConfigError as exc:
        print(f"config/cycle.yaml or the registry: {exc}", file=sys.stderr)
        return 2
    if a.check:
        if not OUT.exists() or OUT.read_text() != wanted:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python scripts/render_cycle.py", file=sys.stderr)
            return 1
        print("cycle up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(wanted)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
